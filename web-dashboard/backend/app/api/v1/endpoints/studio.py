"""Live production studio with isolated departments and downloadable artifacts.

The first production implementation intentionally provides deterministic local
outputs that work without paid providers. Provider-backed image, video and 3D
renderers can replace a department adapter without changing the public contract.
"""

from __future__ import annotations

import io
import json
import re
import textwrap
import zipfile
from datetime import UTC, datetime
from typing import Literal

from app.core.auth import UserRecord, current_user
from fastapi import APIRouter, Depends, HTTPException, status
from fastapi.responses import StreamingResponse
from pydantic import BaseModel, Field

router = APIRouter()

Department = Literal[
    "website",
    "code",
    "ui-ux",
    "three-d",
    "video",
    "animation",
    "advertising",
    "documentary",
    "image",
    "branding",
]

DEPARTMENTS: tuple[dict[str, object], ...] = (
    {"id": "website", "name": "Website Studio", "outputs": ["HTML", "CSS", "JavaScript", "ZIP"]},
    {"id": "code", "name": "Code Studio", "outputs": ["source", "tests", "README", "ZIP"]},
    {"id": "ui-ux", "name": "UI/UX Studio", "outputs": ["design system", "wireframe", "prototype brief"]},
    {"id": "three-d", "name": "3D & Three.js Studio", "outputs": ["Three.js scene", "GLTF-ready structure", "ZIP"]},
    {"id": "video", "name": "Video Studio", "outputs": ["script", "shot list", "subtitles", "render plan"]},
    {"id": "animation", "name": "Animation Studio", "outputs": ["storyboard", "timing sheet", "scene plan"]},
    {"id": "advertising", "name": "Advertising Studio", "outputs": ["campaign brief", "ad variants", "CTA plan"]},
    {"id": "documentary", "name": "Documentary Studio", "outputs": ["research outline", "narration", "evidence checklist"]},
    {"id": "image", "name": "Image Studio", "outputs": ["editable SVG", "prompt pack", "export guide"]},
    {"id": "branding", "name": "Branding Studio", "outputs": ["brand strategy", "identity tokens", "usage guide"]},
)


class StudioRequest(BaseModel):
    department: Department
    title: str = Field(min_length=2, max_length=160)
    brief: str = Field(min_length=8, max_length=12_000)
    language: str = Field(default="en-US", max_length=35)
    style: str = Field(default="modern", max_length=80)
    target: str | None = Field(default=None, max_length=160)
    programming_language: str | None = Field(default=None, max_length=40)


def _slug(value: str) -> str:
    normalized = re.sub(r"[^a-zA-Z0-9]+", "-", value.strip()).strip("-").lower()
    return normalized[:70] or "aionex-project"


def _readme(data: StudioRequest) -> str:
    return textwrap.dedent(
        f"""\
        # {data.title}

        Generated by AIONEX AIOS Production Studio.

        - Department: {data.department}
        - Language: {data.language}
        - Style: {data.style}
        - Target: {data.target or 'General audience'}
        - Generated: {datetime.now(UTC).isoformat()}

        ## Brief

        {data.brief}

        ## Production note

        This downloadable package is a deterministic, editable starting point.
        External AI provider adapters may add photorealistic images, rendered
        video, voice cloning, music, or hosted deployment when configured and
        approved by platform governance.
        """
    )


