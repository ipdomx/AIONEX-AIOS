def _strategy_files(data: StudioRequest) -> dict[str, str]:
    sections = {
        "ui-ux": ["User problem", "Personas", "Information architecture", "Wireframes", "Design tokens", "Accessibility", "Usability tests"],
        "animation": ["Concept", "Characters", "Storyboard", "Timing", "Key poses", "Transitions", "Sound design"],
        "advertising": ["Product truth", "Audience", "Campaign promise", "Hooks", "Formats", "Calls to action", "Measurement"],
        "documentary": ["Central question", "Research sources", "Interview plan", "Narrative arc", "Fact checking", "Rights and releases", "Distribution"],
        "branding": ["Purpose", "Positioning", "Audience", "Voice", "Visual system", "Logo usage", "Launch plan"],
    }[data.department]
    content = [f"# {data.title}", "", f"Brief: {data.brief}", "", f"Style: {data.style}", ""]
    for index, section in enumerate(sections, start=1):
        content.extend([f"## {index}. {section}", "", "- Decision:", "- Evidence:", "- Deliverable:", ""])
    return {"production-plan.md": "\n".join(content)}


def _code_files(data: StudioRequest) -> dict[str, str]:
    language = (data.programming_language or "python").lower()
    if language in {"javascript", "typescript"}:
        extension = "ts" if language == "typescript" else "js"
        code = f"export function projectSummary() {{ return {json.dumps(data.brief)}; }}\nconsole.log(projectSummary());\n"
        test = "import { projectSummary } from './src/index';\nif (!projectSummary()) throw new Error('summary missing');\n"
        return {f"src/index.{extension}": code, f"tests/basic.{extension}": test, "package.json": json.dumps({"name": _slug(data.title), "version": "1.0.0", "private": True, "scripts": {"test": f"node tests/basic.{extension}"}}, indent=2)}
    code = f'''"""{data.title}."""\n\ndef project_summary() -> str:\n    return {data.brief!r}\n\nif __name__ == "__main__":\n    print(project_summary())\n'''
    test = "from src.main import project_summary\n\ndef test_project_summary():\n    assert project_summary().strip()\n"
    return {"src/main.py": code, "tests/test_main.py": test, "requirements.txt": "pytest==8.3.5\n"}


def _department_files(data: StudioRequest) -> dict[str, str]:
    if data.department == "website":
        return _website_files(data)
    if data.department == "code":
        return _code_files(data)
    if data.department == "three-d":
        return _three_files(data)
    if data.department in {"video"}:
        return _video_files(data)
    if data.department == "image":
        return _image_files(data)
    return _strategy_files(data)


@router.get("/departments")
async def departments() -> dict[str, object]:
    return {"departments": DEPARTMENTS, "count": len(DEPARTMENTS)}


@router.post("/generate")
async def generate_artifact(
    data: StudioRequest,
    actor: UserRecord = Depends(current_user),
) -> StreamingResponse:
    if not data.brief.strip():
        raise HTTPException(status_code=status.HTTP_422_UNPROCESSABLE_ENTITY, detail="Brief is required")

    files = {"README.md": _readme(data), **_department_files(data)}
    manifest = {
        "schema": "aionex.production-artifact.v1",
        "department": data.department,
        "title": data.title,
        "language": data.language,
        "style": data.style,
        "created_by": actor.id,
        "created_at": datetime.now(UTC).isoformat(),
        "files": sorted(files),
    }
    files["aionex-manifest.json"] = json.dumps(manifest, ensure_ascii=False, indent=2)

    archive = io.BytesIO()
    with zipfile.ZipFile(archive, "w", compression=zipfile.ZIP_DEFLATED) as bundle:
        for path, content in files.items():
            bundle.writestr(path, content)
    archive.seek(0)
    filename = f"{_slug(data.title)}-{data.department}.zip"
    return StreamingResponse(
        archive,
        media_type="application/zip",
        headers={
            "Content-Disposition": f'attachment; filename="{filename}"',
            "X-AIONEX-Department": data.department,
            "Cache-Control": "no-store",
        },
    )
